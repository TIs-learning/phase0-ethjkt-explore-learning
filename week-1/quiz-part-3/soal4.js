// ### 4. Type Conversion
// 
// Buat variabel:
// 
// ```javascript
// let angka = "100";
// ```
// 
// Lakukan konversi menjadi:
// 
// * Number
// * String kembali
// * Boolean
// 
// Lalu amati hasil `typeof` masing-masing.

let angka = "100"

let angka2  = Number(angka)
let Str =  String(angka)
let bool = Boolean(angka)

console.log(typeof angka2)
console.log(typeof Str)
console.log(typeof bool)